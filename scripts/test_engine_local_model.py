"""Offline protocol tests; actual local-model evidence is recorded separately."""
import argparse
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import subprocess
import unittest
from unittest.mock import patch

spec = importlib.util.spec_from_file_location('local_model', Path(__file__).with_name('engine-local-model.py'))
local = importlib.util.module_from_spec(spec)
spec.loader.exec_module(local)


class LocalModelTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / 'coding-work').mkdir()
        self.args = argparse.Namespace(directory=self.root, endpoint='http://127.0.0.1:11435', model='installed:small',
                                       out=self.root / 'proposal.json', max_output_tokens=1024, timeout_seconds=20)
        self.request = {'protocol': 'tsr-proposal@v1', 'state_root': 'current', 'instructions': 'public instructions',
                        'pending': None, 'coding': {'generated_edits': True, 'kind': 'rust_project@v1',
                        'files': [{'path': 'src/lib.rs', 'editable': True, 'source_digest': 'digest', 'inspection_handle': 'handle', 'source': 'old'}]}}
        self.proposal = {'protocol': 'tsr-proposal@v1', 'state_root': 'current',
                         'proposals': [{'kind': 'edit_set', 'patches': [{'path': 'src/lib.rs', 'source_digest': 'digest', 'inspection_handle': 'handle', 'old_text': 'old', 'new_text': 'new'}], 'rationale': 'model proposal'}]}
        self.reply = {'done': True, 'done_reason': 'stop', 'eval_count': 100, 'prompt_eval_count': 200,
                      'message': {'role': 'assistant', 'content': json.dumps({'edits': [{'path': 'src/lib.rs', 'replacement': 'new'}], 'rationale': 'model proposal'})}}
        self.model = {'name': 'installed:small', 'digest': 'local-digest', 'size': 100}
        self.calls = []

    def api(self, request, timeout):
        self.calls.append(request)
        self.assertFalse(request.has_header('Authorization'))
        if request.full_url.endswith('/api/tags'):
            return io.BytesIO(json.dumps({'models': [self.model]}).encode())
        self.assertEqual(request.full_url, 'http://127.0.0.1:11435/api/chat')
        body = json.loads(request.data)
        self.assertEqual(body['messages'][1]['content'], json.dumps(local.model_context(self.request)))
        self.assertEqual(body['keep_alive'], 0)
        self.assertNotIn('tools', body)
        return io.BytesIO(json.dumps(self.reply).encode())

    def test_supporting_context_is_observation_without_patch_authority(self):
        self.request['coding']['supporting_context'] = [{'path': 'src/contract.rs', 'editable': False,
            'source': 'const LIMIT: u32 = 100;', 'source_digest': 'bound', 'authority': 'read only'}]
        context = local.model_context(self.request)
        self.assertFalse(context['coding']['supporting_context'][0]['editable'])
        self.assertEqual(context['coding']['supporting_context'][0]['source'], 'const LIMIT: u32 = 100;')
        self.assertNotIn('source_digest', context['coding']['supporting_context'][0])
        with self.assertRaises(ValueError):
            local.bind_proposal(self.request, json.dumps({'edits': [{'path': 'src/contract.rs', 'replacement': 'bad'}], 'rationale': 'not allowed'}))
        self.assertEqual(local.response_schema(self.request)['properties']['edits']['items']['properties']['path']['enum'], ['src/lib.rs'])

    def test_project_possibilities_preserve_generated_meaning_and_current_bindings(self):
        self.request['coding']['relational'] = {'binding': 'evidence-root',
            'inputs': {'snapshot': 'source-root', 'requirements_revision': 'criteria-root', 'parents': []},
            'guidance': [{'proposal': {'aspiration': 'fixture meaning'}}]}
        self.assertEqual(local.model_context(self.request)['coding']['relational'], self.request['coding']['relational'])
        hypothesis = {'parents': ['a', 'b'], 'relationship': 'fixture relation', 'aspiration': 'fixture aspiration',
                      'discriminator': 'fixture distinction', 'revises': None, 'catalysts': []}
        bound = local.bind_proposal(self.request, json.dumps({'relational': hypothesis}))
        self.assertEqual(bound['proposals'][0], {'kind': 'relational', 'binding': 'evidence-root', 'proposal': hypothesis})
        experiment = {'harness': {'tests/tsr_supplemental_x.rs': 'generated bytes'}, 'cases': [], 'mapping': {}}
        bound = local.bind_proposal(self.request, json.dumps({'experiment': experiment}))
        self.assertEqual(bound['proposals'][0]['experiment'], dict(experiment, binding='evidence-root', snapshot='source-root', requirements_revision='criteria-root'))
        for extra in ('binding', 'snapshot', 'review', 'authority'):
            with self.assertRaises(ValueError):
                local.bind_proposal(self.request, json.dumps({'experiment': dict(experiment, **{extra: 'invented'})}))
        # Fake provider/validator only; actual Rust admission/identity checks have separate tests.
        self.args.possibilities = True
        self.reply['message']['content'] = json.dumps({'relational': hypothesis})
        result = self.run_fixture({'assessments': [{'disposition': 'deferred'}]})
        self.assertEqual(result['status'], 'review_required')
        self.assertFalse(result['executed'])
        self.assertEqual(json.loads(self.args.out.read_text())['proposals'][0]['proposal'], hypothesis)
        body = json.loads(self.calls[-1].data)
        self.assertEqual(body['format'], 'json')
        self.assertIn('never automatically executed', body['messages'][0]['content'])

    def run_fixture(self, validation=None):
        with patch.object(local.urllib.request, 'build_opener') as opener, patch.object(local.runner, 'cli') as cli, patch.object(local.subprocess, 'run') as check:
            opener.return_value.open.side_effect = self.api
            cli.return_value = self.request
            check.return_value = subprocess.CompletedProcess([], 0, json.dumps(validation or {'assessments': [{'disposition': 'eligible'}]}).encode(), b'')
            result = local.run(self.args)
            self.assertIn('propose', check.call_args.args[0])
            self.assertNotIn('--apply', check.call_args.args[0])
            return result

    def budget_fixture(self, failure=None):
        records = []
        def cli(directory, command, *args):
            if command == 'request': return self.request
            if command == 'project-budget': return {'active': True}
            value = json.loads(Path(args[1]).read_text())
            records.append((command, value))
            if command == 'project-resource-reserve':
                self.assertFalse(any(r.full_url.endswith('/api/chat') for r in self.calls))
                if failure == 'reserve': raise ValueError('budget refused')
                return {'limits': {'wall_ms': 60000}, 'elapsed_wall_ms': 1}
            if failure == 'settle': raise local.runner.Stop('uncertain settlement')
            return {'active': True}
        def api(request, timeout):
            if request.full_url.endswith('/api/chat') and failure == 'timeout':
                self.calls.append(request)
                raise TimeoutError('bounded timeout')
            return self.api(request, timeout)
        with patch.object(local.urllib.request, 'build_opener') as opener, patch.object(local.runner, 'cli', side_effect=cli), patch.object(local.subprocess, 'run') as check:
            opener.return_value.open.side_effect = api
            check.return_value = subprocess.CompletedProcess([], 0, json.dumps({'assessments': [{'disposition': 'eligible'}]}).encode(), b'')
            if failure:
                with self.assertRaises(Exception): local.run(self.args)
            else: local.run(self.args)
        return records

    def test_prospective_local_usage_is_reserved_then_measured(self):
        records = self.budget_fixture()
        self.assertEqual([r[0] for r in records], ['project-resource-reserve', 'project-resource-settle'])
        self.assertEqual(records[1][1]['prompt_tokens'], 200)
        self.assertEqual(records[1][1]['output_tokens'], 100)
        self.assertEqual(records[1][1]['external_cost_microusd'], 0)

    def test_timeout_keeps_explicit_unknown_usage(self):
        records = self.budget_fixture('timeout')
        self.assertEqual(records[-1][1]['outcome'], 'unknown')
        self.assertIsNone(records[-1][1]['prompt_tokens'])
        self.assertEqual(sum(r.full_url.endswith('/api/chat') for r in self.calls), 1)

    def test_uncertain_settlement_is_not_retried_with_different_usage(self):
        records = self.budget_fixture('settle')
        self.assertEqual(sum(c == 'project-resource-settle' for c, _ in records), 1)
        receipt = self.args.out.with_name(self.args.out.name + '.local-receipt.jsonl')
        history = [json.loads(line) for line in receipt.read_text().splitlines()]
        self.assertTrue(any(r['status'] == 'generated_unvalidated' for r in history))
        self.assertTrue(any(r['status'] == 'resource_settlement_intent' for r in history))

    def test_unaccounted_broker_transport_refuses_active_project_budget(self):
        with patch.object(local.runner, 'cli', side_effect=[self.request, {'active': True}]):
            with self.assertRaisesRegex(local.runner.Stop, 'accounted_local_transport'):
                local.runner.run(argparse.Namespace(directory=self.root))

    def test_budget_refusal_prevents_dispatch(self):
        self.budget_fixture('reserve')
        self.assertFalse(any(r.full_url.endswith('/api/chat') for r in self.calls))

    def test_local_generation_validates_without_execution(self):
        result = self.run_fixture()
        self.assertEqual(result['status'], 'proposal_ready')
        self.assertFalse(result['executed'])
        self.assertEqual(json.loads(self.args.out.read_text()), self.proposal)
        events = [json.loads(line) for line in Path(result['receipt']).read_text().splitlines()]
        self.assertEqual([e['status'] for e in events], ['started', 'generated_unvalidated', 'proposal_ready'])
        self.assertEqual(events[0]['paid_calls'], 0)
        self.assertEqual(len(self.calls), 2)
        with self.assertRaises(ValueError):
            local.run(self.args)
        self.assertEqual(len(self.calls), 2)

    def test_truncation_persists_failure_without_output_or_retry(self):
        self.reply['done_reason'] = 'length'
        with self.assertRaises(ValueError):
            self.run_fixture()
        self.assertFalse(self.args.out.exists())
        receipt = self.args.out.with_name(self.args.out.name + '.local-receipt.jsonl')
        self.assertEqual(json.loads(receipt.read_text().splitlines()[-1])['status'], 'failed_no_retry')
        with self.assertRaises(ValueError):
            local.run(self.args)

    def test_missing_or_remote_model_never_generates(self):
        self.model['remote_host'] = 'https://example.invalid'
        with self.assertRaises(ValueError):
            self.run_fixture()
        self.assertEqual(len(self.calls), 1)
        self.assertFalse(self.args.out.exists())

    def test_candidate_workspace_is_not_an_output_target(self):
        self.args.out = self.root / 'coding-work/result.json'
        with self.assertRaises(ValueError):
            local.run(self.args)
        self.assertEqual(self.calls, [])

    def test_unpublished_rejection_never_calls_provider(self):
        self.request['acceptance_cycle'] = {'unmet_count': 1, 'repair_ready': False}
        with self.assertRaises(ValueError):
            self.run_fixture()
        self.assertEqual(self.calls, [])

    def test_excessive_output_tokens_are_refused(self):
        self.reply['eval_count'] = 1025
        with self.assertRaises(ValueError):
            self.run_fixture()
        self.assertFalse(self.args.out.exists())

    def test_no_eligible_action_does_not_produce_runnable_file(self):
        with self.assertRaises(ValueError):
            self.run_fixture({'assessments': [{'disposition': 'deferred'}]})
        self.assertFalse(self.args.out.exists())

    def test_no_eligible_attention_stops_before_provider_or_reservation(self):
        self.request['next_attention'] = {'focus': {'kind': 'no_eligible_attention'}}
        with patch.object(local.urllib.request, 'build_opener') as opener, patch.object(local.runner, 'cli', return_value=self.request) as cli:
            with self.assertRaisesRegex(ValueError, 'no eligible residual attention'):
                local.run(self.args)
            opener.return_value.open.assert_not_called()
            self.assertFalse(any('project-resource-reserve' in call.args for call in cli.call_args_list))

    def test_attention_reaches_context_and_response_without_private_report(self):
        self.request['next_attention'] = {'version': 'proposal-attention@v1', 'binding': 'frozen',
                                         'focus': {'kind': 'admitted_preference', 'criterion': 'subtotal', 'text': 'Correct subtotal'}}
        context = local.model_context(self.request)
        self.assertEqual(context['next_attention']['focus']['criterion'], 'subtotal')
        self.assertIn('no permission', context['attention_instruction'])
        self.assertNotIn('binding', context['next_attention'])
        value = {'edits': [{'path': 'src/lib.rs', 'replacement': 'new'}], 'rationale': 'model'}
        self.assertEqual(local.bind_proposal(self.request, json.dumps(value))['attention_binding'], 'frozen')

    def test_controller_binds_only_metadata_and_preserves_model_edit_text(self):
        proposed = {'edits': [{'path': 'src/lib.rs', 'replacement': 'model-selected new code'}], 'rationale': 'independent model text'}
        result = local.bind_proposal(self.request, json.dumps(proposed))
        edit = result['proposals'][0]['patches'][0]
        self.assertEqual(edit['old_text'], 'old')
        self.assertEqual(edit['new_text'], 'model-selected new code')
        self.assertEqual(edit['source_digest'], 'digest')
        self.assertEqual(result['state_root'], 'current')
        proposed['edits'][0]['path'] = 'tests/protected.rs'
        with self.assertRaises(ValueError):
            local.bind_proposal(self.request, json.dumps(proposed))
        proposed['edits'][0]['path'] = 'src/lib.rs'
        proposed['edits'][0]['source_digest'] = 'model-forged'
        with self.assertRaises(ValueError):
            local.bind_proposal(self.request, json.dumps(proposed))

    def test_context_keeps_current_contract_and_outcomes_without_binding_bloat(self):
        self.request.update(goal='repair both', acceptance_cycle={'belief': {'a': 0.2}, 'guidance': {'a': 'subtract'}},
                            contrast=[{'id': 'opaque'}] * 1000,
                            prior_outcomes=[{'success': False, 'met': [], 'evidence': str(i)} for i in range(6)])
        self.request['coding']['files'][0]['edit_window'] = {'initial_start': 10, 'initial_end': 13, 'outside_window': 'immutable'}
        context = local.model_context(self.request)
        self.assertEqual(context['coding']['files'][0]['edit_window'], self.request['coding']['files'][0]['edit_window'])
        self.assertEqual(context['acceptance_cycle'], self.request['acceptance_cycle'])
        self.assertEqual(context['coding']['files'][0]['source'], 'old')
        self.assertNotIn('source_digest', context['coding']['files'][0])
        self.assertNotIn('contrast', context)
        self.assertEqual(context['history_window']['outcomes_omitted'], 2)
        self.assertEqual(context['prior_outcomes'][-1]['evidence'], '5')

    def test_current_commitment_and_expectations_reach_local_generator(self):
        self.request.update(current_commitment='previous-choice', frozen_expectations=[{'raw': 0.1}] * 6,
                            estimates=[{'prediction': {'value': 0.2}}], actions=[{'description': 'alternate'}])
        context = local.model_context(self.request)
        self.assertEqual(context['current_commitment'], 'previous-choice')
        self.assertEqual(context['frozen_expectations'], [{'raw': 0.1}] * 4)
        self.assertEqual(context['history_window']['frozen_expectations_omitted'], 2)
        self.assertEqual(context['estimates'], self.request['estimates'])
        self.assertEqual(context['actions'], self.request['actions'])

    def test_unchanged_replacement_is_diagnosed_before_preview(self):
        with self.assertRaisesRegex(ValueError, 'unchanged source'):
            local.bind_proposal(self.request, json.dumps({'edits': [{'path': 'src/lib.rs', 'replacement': 'old'}], 'rationale': 'no-op'}))

    def test_only_literal_loopback_and_no_redirects(self):
        for url in ['https://127.0.0.1:11434', 'http://localhost:11434', 'http://example.com:11434',
                    'http://user:secret@127.0.0.1:11434', 'http://127.0.0.1:11434/private',
                    'http://127.0.0.1:11434/?x=1']:
            with self.subTest(url=url), self.assertRaises(ValueError):
                local.endpoint(url)
        with self.assertRaises(ValueError):
            local.NoRedirect().redirect_request(None, None, 302, '', {}, 'https://example.com')


if __name__ == '__main__':
    unittest.main()
