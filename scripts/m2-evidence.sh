## The store the CLI folds

`fixtures/m2/store/tsr.db` is **not committed** — `.gitignore` has `*.db`, so `git ls-files
fixtures/m2` shows only the thirty JSON episodes. The store is a derived artifact: the generator
writes it only under `TSR_REGEN_FIXTURES=1`, into a fresh copy under `target/` here. The
`reflect`/`review` commands below read that copy.

EOF

run "ls -la $WORK/store/"

