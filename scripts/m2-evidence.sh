#!/usr/bin/env bash
# scripts/m2-evidence.sh — regenerate docs/m2-evidence.md from real command output.
#
# Run from the workspace root:
#     bash scripts/m2-evidence.sh > out.md
#
# Every command block in the output is the real stdout+stderr and exit code of the
# command printed above it. Nothing is hand-edited. The only things that vary
# between runs on the same commit are test timings and the timestamp-derived note
# and record ids (named in the prose below).
set -u

export PATH=/usr/local/cargo/bin:$PATH
export CARGO_HOME=$PWD/.cargo-home

MAIN=82d6b217891fead5762033b74cb7a4a2cdee51ae
ALPHA00=1a26474df3ed1dc847b171c26c9e882d69e891215480fd8ba1bd0bef2345b58b
RETURN=905fedd5f9e146104bd18b1bc0589dac143303999cfcf3d13b0e404076903f32

WORK=target/m2-evidence
STORE=$WORK/store/tsr.db
SCRATCH=$WORK/scratch.db
PENDING=$WORK/pending.db
CLAUDE=$WORK/claude-session.db

# --- run a command, print `$ cmd` then a fenced console block with output + exit code ---
run() {
  local cmd="$1"
  printf '$ %s\n' "$cmd"
  printf '```console\n'
  local out rc
  out=$(eval "$cmd" 2>&1); rc=$?
  printf '%s\n' "$out"
  printf 'exit %d\n' "$rc"
  printf '```\n\n'
}

# --- clean up the fixtures/m2/store symlink on exit so the tree stays clean ---
cleanup() { rm -f fixtures/m2/store; }
trap cleanup EXIT

mkdir -p "$WORK/store"

# =====================================================================
# Header
# =====================================================================
HEAD=$(git rev-parse HEAD)
cat <<EOF
# M2 evidence — fixtures, the seeded generator, and the Mirror

This page is generated by \`scripts/m2-evidence.sh\` at commit \`$HEAD\`. Every command block
below is the script's own output pasted unchanged: the command prefixed \`\$ \`, then its real
stdout and stderr and exit code in a fenced \`console\` block. Nothing here is hand-edited.
Re-running the script on the same commit reproduces every block except test timings and the
timestamp-derived note and record ids.

## What the corpus is, and what it is not

\`fixtures/m2/episodes/\` holds **thirty synthetic episodes** — ten each in three task families
(\`alpha\`, \`beta\`, \`gamma\`). They are produced by a seeded generator,
\`crates/tsr-cli/tests/m2_episodes.rs\`, which drives the store API through the whole cycle:

> open → propose → forecast (generator, controller, operator) → commit → dispatch → execute →
> close → review

**They are synthetic.** No operator session produced them, and no number in them is a measurement of
a real agent. The real thirty episodes come from operator sessions after M3's batch runner. The
corpus exists so that \`tsr reflect --family\` has a curve to draw and so that the M2 commands have a
deterministic input to test against.

The three families differ in the generator's calibration: \`alpha\`'s generator is over-confident
(+0.15 on its raw probability), \`beta\`'s is unbiased (0.0), and \`gamma\`'s is under-confident
(−0.15). The controller and the operator carry no bias, so the generator's curve is the one that
moves between families.

## The generator is deterministic

The seed is \`SEED = 0x5eed_2024_0000_0001\` (\`crates/tsr-cli/tests/m2_episodes.rs\`). Every id, every
probability and every timestamp is a pure function of the seed and the episode index, so the corpus
is reproducible byte for byte.

EOF

# =====================================================================
# (a) the generator tests — all eight
# =====================================================================
run "cargo test -p tsr-cli --test m2_episodes"

cat <<'EOF'
The eight tests are:

- `corpus_is_thirty_episodes_across_three_families` — thirty episodes, ten per family, each with the
  full event sequence.
- `generation_is_deterministic` — two runs from the same seed produce identical events.
- `fixtures_are_committed_and_match_the_generator` — the files on disk equal what the generator
  produces now.
- `d11_fixture_surprise_residual_is_forecast_minus_observed` — the fixture Surprise rows are
  forecast minus observed.
- `store_holds_every_episode_for_the_cli` — the store holds every episode's events and its head root
  is stable across a rebuild.
- `d6_fixture_compare_is_read_only` — a plain run (no `TSR_REGEN_FIXTURES=1`) compares the committed
  JSON and store against a fresh build and **fails** on a mismatch instead of silently refreshing
  them; it leaves `fixtures/m2/episodes/*.json` byte-identical.
- `generator_curve_differs_across_families` — the generator's Brier differs across families, and the
  over-confident family scores worse than the unbiased one.
- `r3_fixture_family_curves_have_nonzero_observed` — the fixture families' reliability bins carry a
  non-zero observed rate (the M2 exit evidence: the generator's calibration curve is visible).

## Regeneration is explicit

The corpus is regenerated only when `TSR_REGEN_FIXTURES=1` is set. Without it the test compares
read-only and never writes the committed files. With it the run passes and leaves the committed
episodes byte-identical (the generator is deterministic). The store is written into a fresh copy
under `target/`, never into `fixtures/`:

EOF

# =====================================================================
# (b) TSR_REGEN_FIXTURES=1 regeneration, episodes byte-identical
# =====================================================================
run "mkdir -p $WORK/store && ln -sfn \"\$PWD/$WORK/store\" fixtures/m2/store"
run "sha256sum fixtures/m2/episodes/*.json > $WORK/before.sha256 && cat $WORK/before.sha256"
run "TSR_REGEN_FIXTURES=1 cargo test -p tsr-cli --test m2_episodes"
run "sha256sum fixtures/m2/episodes/*.json > $WORK/after.sha256 && cat $WORK/after.sha256"
run "diff $WORK/before.sha256 $WORK/after.sha256 && echo 'episodes byte-identical'"

cat <<'EOF'
## Thirty episodes, ten per family

EOF

run "ls fixtures/m2/episodes | wc -l"
run "ls fixtures/m2/episodes | sed 's/-[0-9]*\\.json//' | sort | uniq -c"

cat <<'EOF'
Each file is one episode: the task id, its family, its index, its outcome, and the ordered events.
The first episode of the `alpha` family begins:

EOF

